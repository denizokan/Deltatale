class Constants:
    """
    These values can be accessed by creating an instance of Constants()

    Example:
    ```
    constants = Constants()
    constants.FPS # Returns the FPS value.
    ```
    """

    def __init__(self):
        self.FPS = 30
        self.WIDTH = 640
        self.HEIGHT = 480

        self.PLAYER_SPEED = 4.5
        self.SOUL_SPEED = 4.5
